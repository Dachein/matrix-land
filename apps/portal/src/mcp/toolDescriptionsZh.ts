export function hasToolDescriptionZh(name: string) {
  return Object.hasOwn(TOOL_DESCRIPTIONS_ZH, name);
}

export function toolDescriptionZh(name: string) {
  return TOOL_DESCRIPTIONS_ZH[name] ?? `调用 ${name} 对应的 Workspace MCP 功能。`;
}

export function toolMatchesHandbookQuery(
  tool: { description: string; name: string },
  query: string
) {
  const normalizedQuery = normalizeSearchText(query);
  if (!normalizedQuery) return true;

  return normalizeSearchText(`${tool.name} ${tool.description} ${toolDescriptionZh(tool.name)}`)
    .includes(normalizedQuery);
}

function normalizeSearchText(value: string) {
  return value.normalize("NFKC").trim().toLowerCase();
}
