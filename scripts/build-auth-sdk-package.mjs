import { createHash } from "node:crypto";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawn } from "node:child_process";

const workspace = resolve(import.meta.dirname, "..");
const packageDirectory = join(workspace, "sdk/auth");
const outputDirectory = join(workspace, "workers/apps/src/apps");
const temporaryDirectory = await mkdtemp(join(tmpdir(), "workspace-auth-sdk-"));

try {
  await command("npm", ["run", "build"], packageDirectory);
  await command("npm", ["pack", "--pack-destination", temporaryDirectory], packageDirectory);
  const packageJson = JSON.parse(await readFile(join(packageDirectory, "package.json"), "utf8"));
  const tarballPath = join(temporaryDirectory, `frontier-workspace-auth-${packageJson.version}.tgz`);
  const bytes = await readFile(tarballPath);
  const sha256 = createHash("sha256").update(bytes).digest("hex");

  await writeFile(
    join(outputDirectory, "authSdkPackageData.ts"),
    `// Generated by scripts/build-auth-sdk-package.mjs; do not edit by hand.\nexport const WORKSPACE_AUTH_SDK_PACKAGE_BASE64 = ${JSON.stringify(bytes.toString("base64"))};\n`,
  );
  await writeFile(
    join(outputDirectory, "authSdkPackageMetadata.ts"),
    `// Generated by scripts/build-auth-sdk-package.mjs; do not edit by hand.\nexport const WORKSPACE_AUTH_SDK_EMBEDDED_VERSION = ${JSON.stringify(packageJson.version)};\nexport const WORKSPACE_AUTH_SDK_EMBEDDED_SHA256 = ${JSON.stringify(sha256)};\nexport const WORKSPACE_AUTH_SDK_EMBEDDED_SIZE_BYTES = ${bytes.byteLength};\n`,
  );
  process.stdout.write(`Embedded @frontier-workspace/auth ${packageJson.version} (${bytes.byteLength} bytes, ${sha256})\n`);
} finally {
  await rm(temporaryDirectory, { force: true, recursive: true });
}

function command(executable, args, cwd) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(executable, args, { cwd, stdio: "inherit" });
    child.once("error", reject);
    child.once("exit", (code) => code === 0
      ? resolvePromise()
      : reject(new Error(`${executable} ${args.join(" ")} exited with ${code}`)));
  });
}
