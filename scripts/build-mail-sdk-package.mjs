import { createHash } from "node:crypto";
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawn } from "node:child_process";

const workspace = resolve(import.meta.dirname, "..");
const packageDirectory = join(workspace, "sdk/mail");
const outputDirectory = join(workspace, "workers/apps/src/apps");
const releasesDirectory = join(packageDirectory, "releases");
const temporaryDirectory = await mkdtemp(join(tmpdir(), "workspace-mail-sdk-"));

try {
  const packageJson = JSON.parse(await readFile(join(packageDirectory, "package.json"), "utf8"));
  const guide = JSON.parse(await readFile(join(packageDirectory, "developer-guide.json"), "utf8"));
  const prompt = guide.developmentPrompt.join("\n")
    .replaceAll("{{SDK_VERSION}}", packageJson.version)
    .replaceAll("{{SDK_PACKAGE_URL}}", `https://apps.example.invalid/sdk/workspace-mail/v${packageJson.version}.tgz`);
  await writeFile(join(packageDirectory, "DEVELOPMENT_PROMPT.md"), `${prompt}\n`);
  await command("npm", ["run", "build"], packageDirectory);
  await command("npm", ["pack", "--pack-destination", temporaryDirectory], packageDirectory);
  const tarballPath = join(temporaryDirectory, `frontier-workspace-mail-${packageJson.version}.tgz`);
  const bytes = await readFile(tarballPath);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  await mkdir(releasesDirectory, { recursive: true });
  const archive = { version: packageJson.version, sha256, sizeBytes: bytes.byteLength, base64: bytes.toString("base64") };
  const archivePath = join(releasesDirectory, `${packageJson.version}.json`);
  let previous;
  try { previous = JSON.parse(await readFile(archivePath, "utf8")); }
  catch (error) { if (error.code !== "ENOENT") throw error; }
  if (previous && previous.sha256 !== sha256) throw new Error(`Published @frontier-workspace/mail ${packageJson.version} is immutable; bump its version before changing the package`);
  if (!previous) await writeFile(archivePath, `${JSON.stringify(archive)}\n`);
  const packages = {};
  for (const file of (await readdir(releasesDirectory)).filter(file => file.endsWith(".json")).sort()) {
    const release = JSON.parse(await readFile(join(releasesDirectory, file), "utf8"));
    const releaseBytes = Buffer.from(release.base64, "base64");
    if (file !== `${release.version}.json` || createHash("sha256").update(releaseBytes).digest("hex") !== release.sha256 || releaseBytes.byteLength !== release.sizeBytes) throw new Error(`Invalid immutable mail SDK archive: ${file}`);
    packages[release.version] = release.base64;
  }

  await writeFile(
    join(outputDirectory, "mailSdkPackageData.ts"),
    `// Generated by scripts/build-mail-sdk-package.mjs; do not edit by hand.\nexport const WORKSPACE_MAIL_SDK_PACKAGES: Record<string, string> = ${JSON.stringify(packages)};\n`,
  );
  await writeFile(
    join(outputDirectory, "mailSdkPackageMetadata.ts"),
    `// Generated by scripts/build-mail-sdk-package.mjs; do not edit by hand.\nexport const WORKSPACE_MAIL_SDK_EMBEDDED_VERSION = ${JSON.stringify(packageJson.version)};\nexport const WORKSPACE_MAIL_SDK_EMBEDDED_SHA256 = ${JSON.stringify(sha256)};\nexport const WORKSPACE_MAIL_SDK_EMBEDDED_SIZE_BYTES = ${bytes.byteLength};\n`,
  );
  process.stdout.write(`Embedded @frontier-workspace/mail ${packageJson.version} (${bytes.byteLength} bytes, ${sha256})\n`);
} finally {
  await rm(temporaryDirectory, { force: true, recursive: true });
}

function command(executable, args, cwd) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(executable, args, { cwd, stdio: "inherit" });
    child.once("error", reject);
    child.once("exit", (code) => code === 0
      ? resolvePromise()
      : reject(new Error(`${executable} ${args.join(" ")} exited with ${code}`)));
  });
}
